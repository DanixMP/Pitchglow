import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import basicSsl from '@vitejs/plugin-basic-ssl';
import { defineConfig, type Plugin } from 'vite';

/** Lists every file under `dir`, as forward-slash paths relative to it. */
function listFiles(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listFiles(full, root) : [relative(root, full).replaceAll('\\', '/')];
  });
}

/**
 * Emits `sw.js` at build time: precaches the whole built app (hashed assets, workers, icons) so the
 * installed PWA works offline. Page navigations are network-first; everything else cache-first.
 */
function serviceWorker(): Plugin {
  return {
    name: 'recorder-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const publicDir = join(process.cwd(), 'public');
      const publicFiles = listFiles(publicDir);
      const files = [...Object.keys(bundle), ...publicFiles].filter((f) => f !== 'sw.js').sort();
      // Version from contents, so a changed icon or manifest (same file name) still busts the cache.
      const hash = createHash('sha256');
      for (const out of Object.values(bundle)) hash.update(out.type === 'chunk' ? out.code : out.source);
      for (const f of publicFiles) hash.update(readFileSync(join(publicDir, f)));
      const version = hash.digest('hex').slice(0, 12);
      const precache = ['./', ...files.map((f) => `./${f}`)];
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.ts. Do not edit.
const CACHE = 'recorder-${version}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('recorder-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./', { ignoreVary: true })),
    );
    return;
  }
  // ignoreVary: dev/static servers send "Vary" headers that would otherwise make cached assets miss.
  event.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`,
      });
    },
  };
}

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string };

export default defineConfig(({ mode }) => ({
  // Relative base so the build works from any sub-path (e.g. GitHub Pages /PitchGlow/).
  base: './',
  // Shown in the About panel.
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  plugins: [
    // `--mode lan`: self-signed HTTPS so phones on the same Wi-Fi get microphone access.
    ...(mode === 'lan' ? [basicSsl()] : []),
    serviceWorker(),
  ],
}));
